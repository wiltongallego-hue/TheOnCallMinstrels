"""Build the HyperFrames project from the same timeline.json the Remotion composition uses.

HyperFrames owns frame-accurate media playback, so the per-frame timeline is baked into two layers:
  assets/loop_background.webm – the background plate of every output frame (VP9)
  assets/loop_wizard.webm     – the wizard sprite layer (VP9 with alpha), mirrored/placed per frame
index.html stacks them as two <video> clips."""
import json, os, shutil, subprocess, tempfile
import cv2, numpy as np
REPO=os.environ.get('LOOP_REPO',os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..')))
REMOTION_PUBLIC=os.path.join(REPO,'remotion','public')
PROJ=os.path.join(REPO,'hyperframes','walking-loop')
tl=json.load(open(f'{REMOTION_PUBLIC}/timeline.json'))
fps=tl['fps']; frames=tl['frames']; n=len(frames); W,H=tl['width'],tl['height']
def sprite_layer(s):
    """straight-alpha RGBA layer with sprite s placed exactly like WalkingLoop.tsx places it"""
    img=cv2.imread(f"{REMOTION_PUBLIC}/{s['src']}",cv2.IMREAD_UNCHANGED).astype(np.float32)
    piv=s['pivotX']-s['x']
    left=s['targetX']-(s['w']-piv) if s['mirror'] else s['targetX']-piv
    if s['mirror']: img=img[:,::-1].copy()
    a=img[...,3:4]/255.0
    pre=np.dstack([img[...,:3]*a,a[...,0]])          # premultiply so edges do not pick up black
    M=np.float32([[1,0,left],[0,1,s['y']+s['dy']]])
    w=cv2.warpAffine(pre,M,(W,H),flags=cv2.INTER_LINEAR,borderMode=cv2.BORDER_CONSTANT,borderValue=(0,0,0,0))
    alpha=w[...,3:4]
    rgb=np.where(alpha>1e-4,w[...,:3]/np.maximum(alpha,1e-4),0)
    return np.dstack([rgb,alpha[...,0]*255])
tmp=tempfile.mkdtemp()
os.makedirs(f'{tmp}/bg'); os.makedirs(f'{tmp}/wiz')
for k,e in enumerate(frames):
    shutil.copy(f"{REMOTION_PUBLIC}/{e['bg']}",f'{tmp}/bg/{k:04d}.webp')
    layer=sprite_layer(e['sprite']) if e['sprite'] else np.zeros((H,W,4),np.float32)
    cv2.imwrite(f'{tmp}/wiz/{k:04d}.png',np.clip(layer+0.5,0,255).astype(np.uint8))
os.makedirs(f'{PROJ}/assets',exist_ok=True)
for d in ['bg','sprites']: shutil.rmtree(f'{PROJ}/assets/{d}',ignore_errors=True)
# VP9 rather than H.264: open-source Chromium (preview / check) cannot decode H.264; renders use FFmpeg either way
subprocess.run(['ffmpeg','-loglevel','error','-y','-framerate',str(fps),'-i',f'{tmp}/bg/%04d.webp',
                '-c:v','libvpx-vp9','-pix_fmt','yuv420p','-b:v','0','-crf','14','-row-mt','1','-g','24',
                f'{PROJ}/assets/loop_background.webm'],check=True)
subprocess.run(['ffmpeg','-loglevel','error','-y','-framerate',str(fps),'-i',f'{tmp}/wiz/%04d.png',
                '-c:v','libvpx-vp9','-pix_fmt','yuva420p','-b:v','0','-crf','18','-row-mt','1','-auto-alt-ref','0',
                f'{PROJ}/assets/loop_wizard.webm'],check=True)
shutil.rmtree(tmp)
dur=n/fps
html=f'''<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <title>The On-Call Minstrels — walking loop</title>
    <script src="vendor/gsap.min.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #000; }}
      #root {{ position: relative; width: 100%; height: 100%; overflow: hidden; background: #000; }}
      .layer {{ position: absolute; inset: 0; width: 100%; height: 100%; object-fit: cover; }}
    </style>
  </head>
  <body>
    <!-- Seamless loop: {n} frames at {fps} fps ({dur:g} s). The last frame flows straight into the first.
         Generated by tools/loop_pipeline/build_hyperframes.py from remotion/public/timeline.json. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{dur:g}" data-width="{W}" data-height="{H}" data-fps="{fps}">
      <!-- original gameplay (walk right, arrival) and reconstructed clean plates (stop, walk back) -->
      <video id="loop-background" class="clip layer" src="assets/loop_background.webm" data-start="0" data-duration="{dur:g}" data-track-index="0" muted playsinline></video>
      <!-- the wizard walking back: mirrored RGBA sprites, transparent everywhere else -->
      <video id="loop-wizard" class="clip layer" src="assets/loop_wizard.webm" data-start="0" data-duration="{dur:g}" data-track-index="1" muted playsinline></video>
    </div>
    <script>
      // Both layers are framework-owned media; the timeline only has to exist.
      const tl = gsap.timeline({{ paused: true }});
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
'''
open(f'{PROJ}/index.html','w').write(html)
print('frames',n,'duration',dur, {f: os.path.getsize(f'{PROJ}/assets/{f}') for f in os.listdir(f'{PROJ}/assets')})
